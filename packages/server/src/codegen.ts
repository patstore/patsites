import * as fs from "node:fs";
import * as path from "node:path";
import { getStorageKey } from "./collection-keys.ts";
import { classTypeName, describeModule, schemaExportName } from "./fields.ts";
import type { ContentSnapshot, PatStoreModule } from "./types.ts";

/** Older article HTML still points at the retired Netlify host. */
export function rewriteLegacySiteLinks<T>(value: T): T {
  if (typeof value === "string") {
    return value.replace(
      /https?:\/\/(?:www\.)?koloproktologie\.netlify\.app/gi,
      "https://koloproktologie.org",
    ) as T;
  }
  if (Array.isArray(value)) {
    return value.map((item) => rewriteLegacySiteLinks(item)) as T;
  }
  if (value && typeof value === "object") {
    const copy: Record<string, unknown> = {};
    for (const [key, item] of Object.entries(value)) {
      copy[key] = rewriteLegacySiteLinks(item);
    }
    return copy as T;
  }
  return value;
}

export function writeContentArtifacts(outputDir: string, snapshot: ContentSnapshot): void {
  fs.mkdirSync(outputDir, { recursive: true });
  const rewritten = rewriteLegacySiteLinks(snapshot);
  const modules = Array.isArray(rewritten._modules) ? rewritten._modules : [];
  fs.writeFileSync(
    path.join(outputDir, "build-time-data.json"),
    JSON.stringify(rewritten, null, 2),
    "utf8",
  );
  fs.writeFileSync(path.join(outputDir, "types.ts"), renderTypes(modules, rewritten), "utf8");
  fs.writeFileSync(path.join(outputDir, "schema.ts"), renderSchema(modules), "utf8");
  fs.writeFileSync(path.join(outputDir, "useFindData.ts"), renderHook(modules), "utf8");
  fs.writeFileSync(path.join(outputDir, "index.ts"), renderIndex(modules), "utf8");
}

function renderTypes(modules: PatStoreModule[], snapshot: ContentSnapshot): string {
  const interfaces = modules
    .filter((module) => module.connected_class)
    .map((module) => renderInterface(module))
    .join("\n\n");
  const collectionLines = modules
    .filter((module) => module.connected_class)
    .map((module) => {
      const key = getStorageKey(module.connected_class);
      return `  ${key}?: ${classTypeName(module.connected_class)}[];`;
    })
    .join("\n");
  const extraKeys = Object.keys(snapshot)
    .filter(
      (key) =>
        !key.startsWith("_") &&
        key !== "downloadedFiles" &&
        Array.isArray(snapshot[key]) &&
        !modules.some((module) => getStorageKey(module.connected_class) === key),
    )
    .map((key) => `  ${key}?: Record<string, unknown>[];`)
    .join("\n");

  return `// Generated by @repo/server. Do not edit.
export interface FileRecord {
  __typename?: string;
  name?: string;
  url: string;
}

export type FileClass = FileRecord;

export interface DownloadedFile {
  objectId: string;
  originalUrl: string;
  localPath: string;
  filename: string;
  type: "image" | "document";
  thumbnailPath?: string;
}

${interfaces}

export interface BuildTimeData {
  _meta?: {
    generatedAt: string;
    projectId: string;
    moduleCount: number;
    states: string[] | null;
  };
  _modules?: unknown[];
  downloadedFiles?: DownloadedFile[];
${collectionLines}
${extraKeys}
  [key: string]: unknown;
}
`;
}

function renderInterface(module: PatStoreModule): string {
  const lines = [
    "  objectId: string;",
    "  id?: string;",
    "  createdAt?: string;",
    "  updatedAt?: string;",
  ];
  for (const field of describeModule(module)) {
    const optional = field.required ? "" : "?";
    lines.push(`  ${field.id}${optional}: ${field.tsType};`);
  }
  return `export interface ${classTypeName(module.connected_class)} {\n${lines.join("\n")}\n}`;
}

function renderSchema(modules: PatStoreModule[]): string {
  const unique = uniqueModules(modules);
  const schemas = unique
    .map((module) => {
      const fields = [
        "  objectId: z.string(),",
        "  id: z.string().optional(),",
        "  createdAt: z.string().optional(),",
        "  updatedAt: z.string().optional(),",
        ...describeModule(module).map((field) => `  ${field.id}: ${field.zodExpr},`),
      ];
      return `export const ${schemaExportName(module.connected_class)} = z.looseObject({\n${fields.join("\n")}\n});`;
    })
    .join("\n\n");
  const map = unique
    .map(
      (module) =>
        `  ${module.connected_class}: ${schemaExportName(module.connected_class)},`,
    )
    .join("\n");
  const augmentation = unique
    .map(
      (module) =>
        `    ${module.connected_class}: z.infer<typeof ${schemaExportName(module.connected_class)}>;`,
    )
    .join("\n");

  return `// Generated by @repo/server. Do not edit.
import { z } from "zod";

${schemas}

export const applicationSchemas = {
${map}
} as const;

export type Application = {
  [K in keyof typeof applicationSchemas]: z.infer<(typeof applicationSchemas)[K]>;
};

declare module "@repo/server" {
  interface ApplicationModules {
${augmentation}
  }
}
`;
}

function renderHook(modules: PatStoreModule[]): string {
  const unique = uniqueModules(modules);
  const typeNames = unique.map((module) => classTypeName(module.connected_class));
  const overloads = unique
    .map((module) => {
      const key = getStorageKey(module.connected_class);
      const typeName = classTypeName(module.connected_class);
      return `    function findByClassName(className: "${key}", states?: DataContext["states"]): ${typeName}[];`;
    })
    .join("\n");

  return `// Generated by @repo/server. Do not edit.
import { useMemo } from "react";
import buildTimeData from "./build-time-data.json";
import { filterByStates, readSnapshotRecords, type DataContext } from "@repo/server";
import type { BuildTimeData, ${typeNames.join(", ")} } from "./types";

export function useFindData() {
  const typedData = buildTimeData as BuildTimeData;

  return useMemo(() => {
${overloads}
    function findByClassName(className: string, states?: DataContext["states"]): any[];
    function findByClassName(className: string, states?: DataContext["states"]): any[] {
      const rows = readSnapshotRecords(typedData, className);
      return filterByStates(rows, states ?? null);
    }

    function findByObjectId<T = ${typeNames.join(" | ") || "Record<string, unknown>"}>(
      objectId: string,
    ): T | null {
      for (const [key, value] of Object.entries(typedData)) {
        if (!Array.isArray(value) || key.startsWith("_") || key === "downloadedFiles") {
          continue;
        }
        const found = value.find(
          (item) =>
            !!item &&
            typeof item === "object" &&
            "objectId" in item &&
            item.objectId === objectId,
        );
        if (found) {
          return found as T;
        }
      }
      return null;
    }

    return {
      findByClassName,
      findByObjectId,
      data: typedData,
    };
  }, [typedData]);
}

export type UseFindDataReturn = ReturnType<typeof useFindData>;
`;
}

function renderIndex(modules: PatStoreModule[]): string {
  const typeNames = [
    "BuildTimeData",
    "DownloadedFile",
    "FileRecord",
    "FileClass",
    ...uniqueModules(modules).map((module) => classTypeName(module.connected_class)),
  ];
  return `// Generated by @repo/server. Do not edit.
import buildTimeData from "./build-time-data.json";
import { registerStaticSnapshot } from "@repo/server";

registerStaticSnapshot(buildTimeData);

export { useFindData } from "./useFindData";
export type { UseFindDataReturn } from "./useFindData";
export { applicationSchemas } from "./schema";
export type { Application } from "./schema";
export { default as buildTimeData } from "./build-time-data.json";
export type {
  ${typeNames.join(",\n  ")},
} from "./types";
`;
}

function uniqueModules(modules: PatStoreModule[]): PatStoreModule[] {
  const seen = new Set<string>();
  const unique: PatStoreModule[] = [];
  for (const module of modules) {
    if (!module.connected_class || seen.has(module.connected_class)) {
      continue;
    }
    seen.add(module.connected_class);
    unique.push(module);
  }
  return unique;
}
